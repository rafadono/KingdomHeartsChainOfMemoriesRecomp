#!/usr/bin/env python3
"""Generates src/text_fonts_data.cpp from the Latin subsets of the embedded OFL fonts.

Usage: gen_font_data.py <font1.ttf> <font2.ttf> ... (order = FontFace order in text_fonts.h)
       gen_font_data.py --extra <font1.ttf> ...   (extra families of the HD overlay: src/text_overlay/overlay_fonts_data.cpp;
                                                   order = kBuiltins order in overlay_fonts.cpp)
Subsetting command used (fontTools 4.x):
  python3 -m fontTools.subset F.ttf --unicodes='U+0020-007E,U+00A0-00FF,U+2018,U+2019,U+201C,U+201D,U+2026,U+2013,U+2014' \
      --no-hinting --desubroutinize --layout-features='' --name-IDs='0,1,2,3,13,14' --output-file=F.sub.ttf
See third_party/fonts/README.md for sources, versions and SHA-256 sums.
"""
import sys, os
extra = len(sys.argv) > 1 and sys.argv[1] == "--extra"
if extra:
    del sys.argv[1]
out = ["// GENERATED by tools/gen_font_data.py - do not edit. Fonts: see third_party/fonts/README.md (SIL OFL 1.1).",
       '#include "text_fonts.h"', "", "namespace khcom { namespace textfonts {", ""]
if extra:
    out = ["// GENERATED by tools/gen_font_data.py --extra - do not edit. Fonts: see third_party/fonts/README.md (SIL OFL 1.1).",
           '#include "overlay_fonts_data.h"', "", "namespace khcom { namespace overlay {", ""]
names = []
for path in sys.argv[1:]:
    data = open(path, 'rb').read()
    ident = 'kData' + ''.join(ch for ch in os.path.basename(path).split('.')[0] if ch.isalnum())
    names.append((ident, len(data)))
    out.append("static const unsigned char %s[%d] = {" % (ident, len(data)))
    for i in range(0, len(data), 24):
        out.append("    " + ",".join("0x%02x" % b for b in data[i:i+24]) + ",")
    out.append("};")
    out.append("")
fn_data, fn_size = ("extra_face_data", "extra_face_size") if extra else ("face_data", "face_size")
out.append("const unsigned char* %s(int face) {" % fn_data)
out.append("    switch (face) {")
for i, (ident, n) in enumerate(names):
    out.append("        case %d: return %s;" % (i, ident))
out.append("        default: return nullptr;")
out.append("    }")
out.append("}")
out.append("size_t %s(int face) {" % fn_size)
out.append("    switch (face) {")
for i, (ident, n) in enumerate(names):
    out.append("        case %d: return %d;" % (i, n))
out.append("        default: return 0;")
out.append("    }")
out.append("}")
out.append("")
if extra:
    out.append("int extra_face_count() { return %d; }" % len(names))
    out.append("")
out.append("}} // namespace khcom::overlay" if extra else "}} // namespace khcom::textfonts")
sys.stdout.write("\n".join(out) + "\n")
